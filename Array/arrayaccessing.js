const tools = ["Hammer", "Screwdriver", "Wrench"];

// Accessing elements
console.log(tools[0]); // Output: "Hammer"
console.log(tools[2]); // Output: "Wrench"

// Modifying an element
tools[1] = "Drill";
console.log(tools);    // Output: ["Hammer", "Drill", "Wrench"]

// Checking the total number of items
console.log(tools.length); // Output: 3
